export const EXERCISES: readonly Exercise[] = RAW_EXERCISES.map((e) => {
  const c = CAMERA[e.id];
  return c ? { ...e, camera: { supported: true as const, ...c } } : { ...e, camera: { supported: false as const } };
});

const byId = new Map(EXERCISES.map((e) => [e.id, e]));

export function getExercise(id: string): Exercise | undefined {
  return byId.get(id);
}

export function requireExercise(id: string): Exercise {
  const e = byId.get(id);
  if (!e) throw new Error(`Unknown exercise id: ${id}`);
  return e;
}
